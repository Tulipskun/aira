import { strict as assert } from "node:assert";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const installer = readFileSync(resolve(import.meta.dir, "../install.sh"), "utf8");
assert.match(installer, /^#!\/usr\/bin\/env bash/m);
assert.match(installer, /TOKEN="\$\{DISCORD:-\$\{ISLA_TOKEN:-\}\}"/);
assert.match(installer, /Set your Discord bot token first/);
assert.match(installer, /git clone --depth 1/);
assert.match(installer, /Installing unzip \(required by Bun on Linux\)/);
assert.match(installer, /git -C "\$INSTALL_ROOT" pull --ff-only/);
assert.match(installer, /AIRA_REPO_URL/);
assert.match(installer, /bun install --frozen-lockfile/);
assert.match(installer, /bun run scripts\/register-commands\.ts/);
assert.match(installer, /scripts\/supervisor\.ts start/);
assert.match(installer, /AIRA_TOKEN_TO_SAVE/);
assert.match(installer, /chmodSync\(file, 0o600\)/);
assert.doesNotMatch(installer, /aira setup/);
assert.doesNotMatch(installer, /bun run install-cli/);
assert.doesNotMatch(installer, /gh auth login/);
console.log("installer tests: OK");
