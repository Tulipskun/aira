import { strict as assert } from "node:assert";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
const entrypoint = readFileSync(resolve(import.meta.dir, "../index.js"), "utf8");
assert.match(entrypoint, /bun.*install.*--frozen-lockfile/);
assert.match(entrypoint, /process\.env\.DISCORD/);
assert.match(entrypoint, /scripts\/register-commands\.ts/);
assert.match(entrypoint, /bun.*run.*start/);
assert.match(entrypoint, /stdio: "inherit"/);
assert.match(readFileSync(resolve(import.meta.dir, "supervisor.ts"), "utf8"), /stdio: "inherit"/);
assert.doesNotMatch(entrypoint, /curl/);
console.log("Pterodactyl startup tests: OK");
